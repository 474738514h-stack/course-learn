import { useCallback, useEffect, useMemo, useRef, useState, type ReactNode } from 'react'
import {
  ArrowLeft,
  Sparkles,
  Loader2,
  RefreshCw,
  BookOpen,
  ChevronRight,
  Target,
  ListChecks,
} from 'lucide-react'
import type { Course, KnowledgePoint, Lesson, LessonSummary } from '../types'
import { buildExerciseActionItems } from '../services/lessonActionItems'
import { buildLessonSummaryContext } from '../services/lessonSummaryContext'
import {
  generateLessonSummary,
  transcriptSummaryHighlights,
} from '../services/lessonSummary'
import {
  buildHistoricalLessonLinks,
  getSortedLessonHits,
} from '../services/lessonSummaryLinks'
import { MindMapView } from './MindMapView'
import { buildVideoTranscriptMindMap } from '../services/transcriptMindMap'
import type { LessonFocusStructured } from '../types'
import { enrichKebanSummaryFromMarkdown } from '../services/kebanReviewImport'
import {
  isReviewMarkdownImport,
  stripVendorNameFromCopy,
} from '../utils/importedCourseCopy'

const SUMMARY_PAGE_WIDTH =
  'w-full max-w-[1080px] mx-auto px-6 md:px-8'

interface LessonSummaryPanelProps {
  course: Course
  lesson: Lesson
  courses: Course[]
  knowledgePoints: KnowledgePoint[]
  onClose: () => void
  onSaveSummary: (
    summary: LessonSummary,
    patch?: { knowledgePointHits?: Record<string, number> }
  ) => void
  onNavigateToLesson: (courseId: string, lessonId: string) => void
}

export function LessonSummaryPanel({
  course,
  lesson,
  courses,
  knowledgePoints,
  onClose,
  onSaveSummary,
  onNavigateToLesson,
}: LessonSummaryPanelProps) {
  const hasTranscript = lesson.transcriptSegments.length > 0
  const [summary, setSummary] = useState<LessonSummary | null>(
    () => (hasTranscript ? null : lesson.summary ?? null)
  )
  const [loading, setLoading] = useState(hasTranscript)
  const [error, setError] = useState<string | null>(null)
  const autoGeneratedRef = useRef(false)

  const ctx = useMemo(
    () => buildLessonSummaryContext(course, lesson, knowledgePoints),
    [course, lesson, knowledgePoints]
  )

  const hitRows = useMemo(
    () => getSortedLessonHits(lesson, knowledgePoints),
    [lesson, knowledgePoints]
  )

  const isReviewImport = isReviewMarkdownImport({
    description: course.description,
    lessons: [{ summary: lesson.summary }],
  })

  const hitDisplayRows = useMemo(() => {
    if (hitRows.length > 0) return hitRows
    const clues = summary?.lessonFocusStructured?.knowledgeClues ?? []
    return clues.map((c, i) => ({
      id: `keban-clue-${i}`,
      term: c.term,
      count: c.count ?? 0,
      description: c.detail,
    }))
  }, [hitRows, summary?.lessonFocusStructured?.knowledgeClues])

  const historyLinks = useMemo(
    () =>
      buildHistoricalLessonLinks(
        courses,
        course.id,
        lesson.id,
        hitRows.map((h) => h.id),
        knowledgePoints
      ),
    [courses, course.id, lesson.id, hitRows, knowledgePoints]
  )

  const display = useMemo(
    () => normalizeSummaryDisplay(summary, ctx),
    [summary, ctx]
  )

  const focusStructured = useMemo(
    () =>
      resolveLessonFocusStructured(
        summary,
        hitDisplayRows,
        ctx.transcript,
        isReviewImport
      ),
    [summary, hitDisplayRows, ctx.transcript, isReviewImport]
  )

  const transcriptRevision = useMemo(
    () =>
      lesson.transcriptSegments.reduce(
        (n, s) => n + s.text.length + s.id.length,
        lesson.transcriptSegments.length
      ),
    [lesson.transcriptSegments]
  )

  /** 仅由视频转写实时提炼，与下方「课程总结」生成结果无关 */
  const videoMindMap = useMemo(() => {
    if (!hasTranscript) return null
    return buildVideoTranscriptMindMap(ctx.transcript, lesson.title)
  }, [hasTranscript, ctx.transcript, lesson.title, transcriptRevision])

  const runGenerate = useCallback(async () => {
    if (!hasTranscript && isReviewImport && lesson.summary) {
      setError(
        '本课来自课程复盘导入且无课堂转写，已保留导入正文；补充转写后再生成可叠加 AI 总结。'
      )
      const { summary: enriched, knowledgePointHits } =
        enrichKebanSummaryFromMarkdown(lesson.summary, knowledgePoints)
      setSummary(enriched)
      onSaveSummary(enriched, { knowledgePointHits })
      return
    }
    setLoading(true)
    setError(null)
    try {
      const result = await generateLessonSummary(ctx)
      setSummary(result)
      onSaveSummary(result)
    } catch (e) {
      setError(e instanceof Error ? e.message : '生成失败')
    } finally {
      setLoading(false)
    }
  }, [
    ctx,
    onSaveSummary,
    hasTranscript,
    isReviewImport,
    lesson.summary,
    knowledgePoints,
  ])

  useEffect(() => {
    autoGeneratedRef.current = false
  }, [lesson.id, transcriptRevision])

  useEffect(() => {
    if (!hasTranscript) {
      if (lesson.summary?.fullMarkdown?.includes('## 课程重点')) {
        const { summary: enriched, knowledgePointHits } =
          enrichKebanSummaryFromMarkdown(lesson.summary, knowledgePoints)
        const needsSave =
          !lesson.summary.lessonFocusStructured?.conclusions.length ||
          Object.keys(knowledgePointHits).length >
            Object.keys(lesson.knowledgePointHits).length
        if (needsSave) {
          onSaveSummary(enriched, { knowledgePointHits })
        }
        setSummary(enriched)
      } else {
        setSummary(lesson.summary ?? null)
      }
      setLoading(false)
      return
    }
    if (autoGeneratedRef.current) return
    autoGeneratedRef.current = true
    setSummary(null)
    void runGenerate()
  }, [
    hasTranscript,
    lesson.id,
    lesson.summary,
    lesson.knowledgePointHits,
    knowledgePoints,
    onSaveSummary,
    transcriptRevision,
    runGenerate,
  ])

  return (
    <div className="h-screen w-full flex flex-col min-h-0 bg-[#f7f6f3]">
      <header className="fixed top-0 left-0 right-0 z-30 h-[60px] shrink-0 border-b border-notion-border/80 bg-[#f7f6f3]/95 backdrop-blur-sm">
        <div
          className={`${SUMMARY_PAGE_WIDTH} h-full flex items-center gap-3 md:gap-5`}
        >
          <button
            type="button"
            onClick={onClose}
            className="inline-flex items-center gap-1 text-[13px] text-notion-muted hover:text-notion-text transition-colors shrink-0"
          >
            <ArrowLeft size={15} />
            返回
          </button>
          <div className="h-6 w-px bg-notion-border shrink-0 hidden sm:block" />
          <div className="min-w-0 flex-1">
            <h1 className="text-[15px] font-semibold text-notion-text leading-tight truncate">
              课程总结
            </h1>
            <p className="text-xs text-notion-muted leading-tight truncate mt-0.5">
              {course.title}
            </p>
          </div>
        </div>
      </header>

      <div className="flex-1 min-h-0 overflow-y-auto pt-[60px]">
        <div className={`${SUMMARY_PAGE_WIDTH} pt-6 pb-10 space-y-5`}>
        <div className="rounded-2xl border border-notion-border bg-white px-6 py-5 shadow-card flex flex-col sm:flex-row sm:items-start sm:justify-between gap-4">
          <div className="min-w-0">
            <p className="text-[11px] text-notion-muted">
              {stripVendorNameFromCopy(course.description)}
            </p>
            <h2 className="text-lg md:text-xl font-semibold text-notion-text flex items-center gap-2 mt-1">
              <BookOpen size={20} className="text-violet-600 shrink-0" />
              <span className="truncate">{lesson.title} · 本课总结</span>
            </h2>
            {!hasTranscript && (
              <p className="text-xs text-notion-muted mt-2">
                {isReviewImport
                  ? '内容来自课程复盘 Markdown，已按章节结构化展示（导出文件不含全文转写）。'
                  : '建议先有课堂转写再生成总结'}
              </p>
            )}
          </div>
          <button
            type="button"
            disabled={loading}
            onClick={runGenerate}
            className="inline-flex items-center justify-center gap-2 px-4 py-2.5 rounded-xl bg-violet-600 text-white text-sm font-medium hover:bg-violet-700 disabled:opacity-60 shrink-0"
          >
            {loading ? (
              <Loader2 size={16} className="animate-spin" />
            ) : summary ? (
              <RefreshCw size={16} />
            ) : (
              <Sparkles size={16} />
            )}
            {summary ? '重新生成' : '生成本课总结'}
          </button>
        </div>
        {error && <p className="text-xs text-red-600 px-1">{error}</p>}

        <div className="space-y-5">
          {videoMindMap && (
            <SummarySection title="思维导图">
              <p className="text-xs text-notion-muted mb-3">
                仅依据本课视频/音频转写自动提炼，与下方课程总结文案独立、随转写更新
              </p>
              <MindMapView root={videoMindMap} />
            </SummarySection>
          )}

          {summary &&
            !loading &&
            !videoMindMap &&
            summary.mindMap?.children &&
            summary.mindMap.children.length > 0 && (
              <SummarySection title="思维导图">
                <p className="text-xs text-notion-muted mb-3">
                  依据复盘文件「课程重点」章节提炼
                </p>
                <MindMapView root={summary.mindMap} />
              </SummarySection>
            )}

          {!summary && !loading && (
            <div className="rounded-2xl border border-notion-border bg-white shadow-card px-8 py-16 text-center text-notion-muted text-sm leading-relaxed">
              点击标题栏「生成本课总结」，将生成课程摘要、课堂重点、笔记阅读版、
              命中知识点与可执行的查漏补缺动作。思维导图已在上方随转写生成。
            </div>
          )}

          {loading && (
            <div className="rounded-2xl border border-notion-border bg-white shadow-card flex flex-col items-center justify-center py-24 gap-3 text-notion-muted">
              <Loader2 size={28} className="animate-spin text-violet-500" />
              <p className="text-sm">正在分析本课内容与你的学习轨迹…</p>
            </div>
          )}

          {summary && !loading && (
            <>
              {display.coreSummary && display.coreSummary !== '_暂无摘要_' && (
                <SummarySection title="核心定调">
                  <p className="text-xs text-notion-muted mb-3">
                    一句话核心与完整摘要
                  </p>
                  <ProseMarkdown content={display.coreSummary} />
                </SummarySection>
              )}

              <SummarySection title="课程重点">
                <p className="text-xs text-notion-muted mb-4">
                  课堂结论与内容启发 · 以知识点为线索
                </p>
                <LessonFocusStructuredView data={focusStructured} />
              </SummarySection>

              <SummarySection title="课堂笔记">
                <p className="text-xs text-notion-muted mb-3">课堂笔记阅读版</p>
                <ProseMarkdown content={display.notesReading} />
              </SummarySection>

              <SummarySection title="命中知识点">
                {hitDisplayRows.length === 0 ? (
                  <p className="text-sm text-notion-muted">
                    {isReviewImport
                      ? '复盘文件中未解析到知识点命中行。'
                      : '本课转写暂未命中知识点。'}
                  </p>
                ) : (
                  <ul className="space-y-2">
                    {hitDisplayRows.map((row) => (
                      <li
                        key={row.id}
                        className="rounded-xl border border-notion-border px-4 py-3 bg-notion-sidebar/30"
                      >
                        <div className="flex items-center justify-between gap-3">
                          <span className="font-medium text-notion-text">
                            {row.term}
                          </span>
                          <span className="text-xs bg-blue-100 text-blue-700 px-2 py-0.5 rounded-full font-medium tabular-nums shrink-0">
                            {row.count} 次
                          </span>
                        </div>
                        {row.description ? (
                          <p className="text-xs text-notion-muted mt-1.5 leading-relaxed">
                            {row.description}
                          </p>
                        ) : null}
                      </li>
                    ))}
                  </ul>
                )}
              </SummarySection>

              <SummarySection title="与历史课程关联">
                {historyLinks.length === 0 ? (
                  <p className="text-sm text-notion-muted">
                    其它课节中尚未出现相同知识点命中，继续学习后将自动串联。
                  </p>
                ) : (
                  <ul className="space-y-2">
                    {historyLinks.map((link) => (
                      <li key={`${link.courseId}-${link.lessonId}`}>
                        <button
                          type="button"
                          onClick={() =>
                            onNavigateToLesson(link.courseId, link.lessonId)
                          }
                          className="w-full text-left rounded-xl border border-notion-border px-4 py-3 hover:bg-notion-hover transition-colors group"
                        >
                          <div className="flex items-center justify-between gap-2">
                            <div className="min-w-0">
                              <p className="text-sm font-medium text-notion-text truncate">
                                {link.lessonTitle}
                              </p>
                              <p className="text-xs text-notion-muted truncate mt-0.5">
                                {link.courseTitle} · 共同：{link.sharedTerms.join('、')}
                              </p>
                            </div>
                            <ChevronRight
                              size={16}
                              className="text-notion-muted group-hover:text-violet-600 shrink-0"
                            />
                          </div>
                        </button>
                      </li>
                    ))}
                  </ul>
                )}
              </SummarySection>

              <SummarySection title="课程行动">
                <p className="text-xs text-notion-muted mb-3 flex items-center gap-1">
                  <Target size={12} />
                  本课配套习题与动手任务，可直接动笔完成（非听课操作建议）
                </p>
                {display.actionItems.length === 0 ? (
                  <p className="text-sm text-notion-muted">暂无行动项，请重新生成总结。</p>
                ) : (
                  <ol className="space-y-2">
                    {display.actionItems.map((item, i) => (
                      <li
                        key={i}
                        className="flex gap-3 text-sm text-notion-text leading-relaxed rounded-xl border border-violet-100 bg-violet-50/40 px-4 py-3"
                      >
                        <ListChecks
                          size={16}
                          className="text-violet-600 shrink-0 mt-0.5"
                        />
                        <span>{item}</span>
                      </li>
                    ))}
                  </ol>
                )}
              </SummarySection>

              <p className="text-[10px] text-notion-muted text-center pt-2">
                生成于 {new Date(summary.generatedAt).toLocaleString('zh-CN')}
              </p>
            </>
          )}
        </div>
        </div>
      </div>
    </div>
  )
}

function LessonFocusStructuredView({ data }: { data: LessonFocusStructured }) {
  return (
    <div className="space-y-4">
      <FocusBlock title="课堂结论" tone="violet">
        {data.conclusions.length === 0 ? (
          <EmptyLine>暂无结论，完成转写后重新生成。</EmptyLine>
        ) : (
          <ul className="space-y-2">
            {data.conclusions.map((item, i) => (
              <li
                key={i}
                className="text-sm text-notion-text leading-relaxed pl-3 border-l-2 border-violet-200"
              >
                {item}
              </li>
            ))}
          </ul>
        )}
      </FocusBlock>

      <FocusBlock title="内容启发" tone="amber">
        {data.inspirations.length === 0 ? (
          <EmptyLine>暂无启发条目。</EmptyLine>
        ) : (
          <ul className="space-y-2">
            {data.inspirations.map((item, i) => (
              <li
                key={i}
                className="text-sm text-notion-text leading-relaxed pl-3 border-l-2 border-amber-200 italic"
              >
                {item}
              </li>
            ))}
          </ul>
        )}
      </FocusBlock>

      <FocusBlock title="知识点线索" tone="blue">
        {data.knowledgeClues.length === 0 ? (
          <EmptyLine>转写暂未命中知识点。</EmptyLine>
        ) : (
          <ul className="space-y-2">
            {data.knowledgeClues.map((clue, i) => (
              <li
                key={i}
                className="rounded-xl border border-notion-border bg-notion-sidebar/40 px-4 py-3"
              >
                <div className="flex items-center justify-between gap-2 mb-1">
                  <span className="font-medium text-notion-text">{clue.term}</span>
                  {clue.count != null && clue.count > 0 && (
                    <span className="text-[10px] bg-blue-100 text-blue-700 px-2 py-0.5 rounded-full font-medium">
                      {clue.count} 次
                    </span>
                  )}
                </div>
                <p className="text-sm text-notion-muted leading-relaxed">
                  {clue.detail}
                </p>
              </li>
            ))}
          </ul>
        )}
      </FocusBlock>
    </div>
  )
}

function FocusBlock({
  title,
  tone,
  children,
}: {
  title: string
  tone: 'violet' | 'amber' | 'blue'
  children: ReactNode
}) {
  const badge =
    tone === 'violet'
      ? 'bg-violet-100 text-violet-800'
      : tone === 'amber'
        ? 'bg-amber-100 text-amber-900'
        : 'bg-blue-100 text-blue-800'

  return (
    <div className="rounded-xl border border-notion-border overflow-hidden">
      <div className={`px-4 py-2 text-xs font-semibold ${badge}`}>{title}</div>
      <div className="px-4 py-3">{children}</div>
    </div>
  )
}

function EmptyLine({ children }: { children: ReactNode }) {
  return <p className="text-sm text-notion-muted">{children}</p>
}

function isStaleHitSeededFocus(
  structured: LessonFocusStructured,
  hitRows: { term: string; description: string }[],
  transcript: string
): boolean {
  const t = transcript.trim()
  if (!t || structured.conclusions.length === 0) return false
  const hitLike = structured.conclusions.filter((c) =>
    hitRows.some(
      (h) => c === `${h.term}：${h.description}` || c.startsWith(`${h.term}：`)
    )
  )
  if (hitLike.length === 0) return false
  return hitLike.some((c) => {
    const row = hitRows.find((h) => c.startsWith(h.term))
    return row != null && !t.includes(row.term)
  })
}

function resolveLessonFocusStructured(
  summary: LessonSummary | null,
  hitRows: { id: string; term: string; count: number; description: string }[],
  transcript: string,
  isReviewImport?: boolean
): LessonFocusStructured {
  const hitsInTranscript = transcript.trim()
    ? hitRows.filter((h) => transcript.includes(h.term))
    : hitRows

  if (
    summary?.lessonFocusStructured &&
  (isReviewImport ||
    !isStaleHitSeededFocus(
      summary.lessonFocusStructured,
      hitRows,
      transcript
    ))
  ) {
    const structured = summary.lessonFocusStructured
    if (structured.knowledgeClues.length > 0) return structured
    return {
      ...structured,
      knowledgeClues: hitsInTranscript.map((h) => ({
        term: h.term,
        count: h.count,
        detail: h.description,
      })),
    }
  }

  if (!summary) {
    return { conclusions: [], inspirations: [], knowledgeClues: [] }
  }

  const fromTranscript = transcript.trim()
    ? transcriptSummaryHighlights(transcript, hitRows)
    : { keyPoints: [], goldenQuotes: [] }

  return {
    conclusions:
      summary.keyPoints.length > 0 &&
      !isStaleHitSeededFocus(
        {
          conclusions: summary.keyPoints,
          inspirations: [],
          knowledgeClues: [],
        },
        hitRows,
        transcript
      )
        ? summary.keyPoints
        : fromTranscript.keyPoints.length > 0
          ? fromTranscript.keyPoints
          : summary.keyPoints,
    inspirations:
      summary.goldenQuotes.length > 0
        ? summary.goldenQuotes
        : fromTranscript.goldenQuotes,
    knowledgeClues: hitsInTranscript.map((h) => ({
      term: h.term,
      count: h.count,
      detail: h.description,
    })),
  }
}

function SummarySection({
  title,
  children,
}: {
  title: string
  children: ReactNode
}) {
  return (
    <section className="rounded-2xl border border-notion-border bg-white shadow-card px-6 md:px-8 py-5">
      <h2 className="text-base font-semibold text-notion-text mb-4">{title}</h2>
      {children}
    </section>
  )
}

function ProseMarkdown({ content }: { content: string }) {
  if (!content.trim()) {
    return <p className="text-sm text-notion-muted">暂无内容</p>
  }

  const blocks = content.split(/\n\n+/)
  return (
    <div className="space-y-3 text-sm text-notion-text leading-relaxed">
      {blocks.map((block, i) => {
        const trimmed = block.trim()
        if (!trimmed) return null
        if (trimmed.startsWith('### ')) {
          return (
            <h4 key={i} className="font-semibold text-notion-text mt-2">
              {trimmed.slice(4)}
            </h4>
          )
        }
        if (trimmed.startsWith('## ')) {
          return (
            <h3 key={i} className="font-semibold text-notion-text">
              {trimmed.slice(3)}
            </h3>
          )
        }
        if (trimmed.startsWith('- ')) {
          const items = trimmed.split('\n').filter((l) => l.startsWith('- '))
          return (
            <ul key={i} className="space-y-1.5 pl-1">
              {items.map((line, j) => (
                <li key={j} className="pl-3 border-l-2 border-violet-200">
                  <InlineMd text={line.slice(2)} />
                </li>
              ))}
            </ul>
          )
        }
        return (
          <p key={i}>
            <InlineMd text={trimmed.replace(/\n/g, ' ')} />
          </p>
        )
      })}
    </div>
  )
}

function InlineMd({ text }: { text: string }) {
  const parts = text.split(/(\*\*[^*]+\*\*)/g)
  return (
    <>
      {parts.map((part, i) =>
        part.startsWith('**') && part.endsWith('**') ? (
          <strong key={i}>{part.slice(2, -2)}</strong>
        ) : (
          <span key={i}>{part}</span>
        )
      )}
    </>
  )
}

function normalizeSummaryDisplay(
  summary: LessonSummary | null,
  ctx: ReturnType<typeof buildLessonSummaryContext>
) {
  if (!summary) {
    return {
      coreSummary: '',
      lessonFocus: '',
      notesReading: '',
      actionItems: [] as string[],
    }
  }

  const coreSummary =
    summary.coreSummary?.trim() ||
    (summary.keyPoints.length
      ? summary.keyPoints.map((p) => `- ${p}`).join('\n')
      : '_暂无摘要_')

  let lessonFocus = summary.lessonFocus?.trim()
  if (!lessonFocus) {
    const parts: string[] = []
    if (summary.keyPoints.length) {
      parts.push('### 课堂结论', ...summary.keyPoints.map((p) => `- ${p}`))
    }
    if (summary.goldenQuotes.length) {
      parts.push('', '### 内容启发', ...summary.goldenQuotes.map((q) => `- ${q}`))
    }
    if (summary.knowledgeMarkdown.trim()) {
      parts.push('', '### 知识点线索', summary.knowledgeMarkdown)
    }
    lessonFocus = parts.join('\n') || '_暂无重点_'
  }

  const notesReading =
    summary.notesReading?.trim() ||
    summary.notesMarkdown?.trim() ||
    (ctx.notes.length
      ? ctx.notes.map((n) => n.content).join('\n\n')
      : '_暂无笔记_')

  const actionItems =
    summary.actionItems && summary.actionItems.length > 0
      ? summary.actionItems
      : buildExerciseActionItems(ctx)

  return { coreSummary, lessonFocus, notesReading, actionItems }
}
